export const PG_SCHEMA_VERSION = MIGRATIONS.length;

/** Lock the schema away from Supabase's API roles (anon / authenticated) if they exist. */
function lockdown(schema: string) {
  return `
  DO $$
  DECLARE t record;
  BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = '${schema}' LOOP
      EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', '${schema}', t.tablename);
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE 'REVOKE ALL ON SCHEMA "${schema}" FROM anon';
      EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA "${schema}" FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
      EXECUTE 'REVOKE ALL ON SCHEMA "${schema}" FROM authenticated';
      EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA "${schema}" FROM authenticated';
    END IF;
  END $$;`;
}

export async function openPostgres(url: string, schema = 'ad_studio', opts: { max?: number } = {}): Promise<Sql> {
  if (!/^[a-z_][a-z0-9_]*$/.test(schema)) throw new Error('Invalid schema name');
  const pool = new Pool({
    connectionString: url,
    max: opts.max ?? 3,
    ssl: /localhost|127\.0\.0\.1/.test(url) ? undefined : { rejectUnauthorized: false },
    options: `-c search_path=${schema},public`,
  });
  // Some poolers ignore startup options, so every new connection also sets the schema before its first query.
  const sql = pgDriver(pool, `SET search_path TO ${schema}, public`);
  await sql.exec(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
  await sql.tx(async () => {
    await sql.exec('SELECT pg_advisory_xact_lock(4242001)'); // one migrator at a time
    await sql.exec(`SET LOCAL search_path TO ${schema}, public`);
    await sql.exec('CREATE TABLE IF NOT EXISTS schema_version (v INTEGER NOT NULL)');
    const rows = await sql.all('SELECT v FROM schema_version');
    let v = rows[0]?.v ?? 0;
    if (!rows.length) await sql.all('INSERT INTO schema_version (v) VALUES (0)');
    while (v < MIGRATIONS.length) { await sql.exec(MIGRATIONS[v]); v += 1; await sql.all('UPDATE schema_version SET v = ?', [v]); }
    await sql.exec(lockdown(schema));
  });
  return sql;
}
